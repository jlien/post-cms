#!/usr/bin/env python3
"""Seed demo posts with media via the real MCP flow.

Generates sample images/video/audio with ffmpeg in /tmp, uploads them through
add_media (SigV4 → MinIO), then creates two published posts embedding the
returned snippets. Exercises the exact tool path an agent would use live.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

import server as mcp  # noqa: E402
import media as media_mod  # noqa: E402

TMP = Path("/tmp/postcms-media-demo")
TMP.mkdir(parents=True, exist_ok=True)


def gen_media() -> dict[str, Path]:
    files = {}

    def run(*cmd: str) -> None:
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"ffmpeg failed: {cmd}\n{res.stderr[-400:]}")

    # hero image: colorful test pattern 1600x900
    hero = TMP / "hero.png"
    if not hero.exists():
        run("ffmpeg", "-y", "-v", "error", "-f", "lavfi",
            "-i", "testsrc2=size=1600x900:rate=1", "-frames:v", "1", str(hero))
    files["hero"] = hero

    # chart-ish image: gradients pattern 960x540
    chart = TMP / "gradients.png"
    if not chart.exists():
        run("ffmpeg", "-y", "-v", "error", "-f", "lavfi",
            "-i", "gradients=size=960x540:rate=1", "-frames:v", "1", str(chart))
    files["chart"] = chart

    # short clip: 4s 640x360 mp4
    clip = TMP / "clip.mp4"
    if not clip.exists():
        run("ffmpeg", "-y", "-v", "error", "-f", "lavfi",
            "-i", "testsrc2=size=640x360:rate=30",
            "-t", "4", "-pix_fmt", "yuv420p", str(clip))
    files["clip"] = clip

    # tone: 3s 440Hz mp3
    tone = TMP / "tone.mp3"
    if not tone.exists():
        run("ffmpeg", "-y", "-v", "error", "-f", "lavfi",
            "-i", "sine=frequency=440:duration=3", "-q:a", "4", str(tone))
    files["tone"] = tone

    return files


def main() -> int:
    files = gen_media()

    # Two posts: one image-led, one video/audio. Both published so they render.
    posts = [
        {
            "slug": "media-pipeline",
            "title": "The Media Pipeline: Binaries Live Elsewhere",
            "tags": ["media", "r2", "architecture"],
            "description": "Images, video, and audio upload to an S3-compatible bucket at publish time; git stays text-only.",
            "media": [
                ("hero", files["hero"], "Test pattern hero image, uploaded through the pipeline"),
                ("chart", files["chart"], "Gradient pattern showing a second image variant set"),
            ],
            "body_tmpl": (
                "# The Media Pipeline\n\n"
                "This post demonstrates the media flow: every binary below was "
                "hashed, resized, and uploaded to an S3-compatible bucket at "
                "*upload time*. Git stores only the reference text.\n\n"
                "## Hero image\n\n"
                "{hero_html}\n\n"
                "## Second image\n\n"
                "{chart_html}\n\n"
                "Images carry `srcset` with 480/960/1600px variants generated by "
                "ffmpeg during `add_media`. The origin server never touches a byte "
                "of media — the browser pulls straight from the bucket/CDN.\n"
            ),
        },
        {
            "slug": "sight-and-sound",
            "title": "Sight and Sound: Embeds Without a Plugin",
            "tags": ["media", "html"],
            "description": "Native video and audio elements, no client JS, no plugin — just URLs from the bucket.",
            "media": [
                ("clip", files["clip"], "Four-second generated test clip"),
                ("tone", files["tone"], "Three-second 440Hz test tone"),
            ],
            "body_tmpl": (
                "# Sight and Sound\n\n"
                "## Video\n\n"
                "{clip_html}\n\n"
                "## Audio\n\n"
                "{tone_html}\n\n"
                "Both are native HTML elements with URLs pointing at the media "
                "bucket. For serious video you'd swap the URL for Mux or "
                "Cloudflare Stream — the stack holds the URL, not the bits.\n"
            ),
        },
    ]

    results = []
    for spec in posts:
        slug = spec["slug"]
        # 1. create draft (via the real MCP handler)
        r = mcp.tool_create_draft({
            "slug": slug, "title": spec["title"],
            "body": "placeholder", "tags": spec["tags"],
            "description": spec["description"],
        })
        assert r.get("created"), r

        # 2. upload each media file via the real handler
        snippets = {}
        for name, path, alt in spec["media"]:
            res = mcp.tool_add_media({
                "slug": slug, "file_path": str(path), "alt": alt,
            })
            assert not res["url"].startswith("error"), res
            snippets[f"{name}_html"] = res["html"]
            snippets[f"{name}_md"] = res["markdown"]
            results.append({"slug": slug, "file": path.name, "url": res["url"],
                            "uploads": len(res["uploads"])})

        # 3. write the real body with embedded snippets, publish
        body = spec["body_tmpl"].format(**snippets)
        upd = mcp.tool_update_post({
            "slug": slug, "body": body, "published": True,
        })
        assert any(c["field"] == "published" for c in upd["changes"]), upd

    print(json.dumps(results, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
